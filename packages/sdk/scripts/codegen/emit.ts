/**
 * Emitters: each returns the full text of one file under `src/generated/`.
 * Pure functions of the document, so a test can assert the committed output
 * is current.
 */
import type { OperationInfo, RouteInfo } from "../../src/core/catalog-types.js";
import { buildEvents, buildOperations, paramsRequired } from "./model.js";
import type { OpenApiDocument } from "./spec.js";
import { buildTree, type TreeNode } from "./tree.js";

const HEADER = "// Generated by scripts/generate.ts from openapi/openapi.json. Do not edit.\n";
const INDENT = "    ";

/** Schema names that would shadow globals or SDK exports. */
const RENAMED_SCHEMAS: Readonly<Record<string, string>> = { Error: "ErrorBody" };

export function schemaAlias(name: string): string {
    return RENAMED_SCHEMAS[name] ?? name;
}

const camel = (s: string): string => s.replace(/_([a-z0-9])/g, (_m, c: string) => c.toUpperCase());

function jsdoc(lines: string[], pad: string): string {
    const body = lines.flatMap((l) => l.split("\n")).map((l) => `${pad} *${l ? ` ${l.replace(/\*\//g, "*\\/")}` : ""}`);
    return `${pad}/**\n${body.join("\n")}\n${pad} */\n`;
}

function opDoc(op: OperationInfo, pad: string): string {
    const lines = [op.summary];
    if (op.description) lines.push("", op.description);
    const scopes = op.scopes.length ? ` · scopes: ${op.scopes.join(", ")}` : "";
    const desktop = op.requiresDesktop ? " · needs Horus Desktop online" : "";
    lines.push("", `\`${op.method} ${op.path}\`${scopes}${desktop}`);
    return jsdoc(lines, pad);
}

function methodSignature(op: OperationInfo): { args: string; call: string; returns: string } {
    const k = JSON.stringify(op.id);
    const pathArgs = op.pathParams.map((p) => `${camel(p.name)}: PathOf<${k}>[${JSON.stringify(p.name)}]`);
    const pathObj = `{ ${op.pathParams.map((p) => `${JSON.stringify(p.name)}: ${camel(p.name)}`).join(", ")} }`.replace("{  }", "{}");
    const paramsType = op.params === "body" ? `BodyOf<${k}>` : `QueryOf<${k}>`;
    const paramsArg = op.params === "none" ? [] : [`params${paramsRequired(op) ? "" : "?"}: ${paramsType}`];
    const args = [...pathArgs, ...paramsArg, "options?: RequestOptions"].join(", ");
    const params = op.params === "none" ? "undefined" : "params";
    if (op.paginated) {
        return { args, call: `r.paginate(${k}, ${pathObj}, ${params}, options)`, returns: `Paginator<ItemOf<${k}>, ResponseOf<${k}>>` };
    }
    return { args, call: `r.call(${k}, ${pathObj}, ${params}, options)`, returns: `Promise<ResponseOf<${k}>>` };
}

function emitNode(node: TreeNode, depth: number): string {
    const pad = INDENT.repeat(depth);
    const parts: string[] = [];
    for (const [name, child] of [...node.children.entries()].sort(([a], [b]) => a.localeCompare(b))) {
        if (child.op) {
            const sig = methodSignature(child.op);
            parts.push(`${opDoc(child.op, pad)}${pad}${name}: (${sig.args}): ${sig.returns} =>\n${pad}${INDENT}${sig.call},\n`);
        } else {
            parts.push(`${pad}${name}: {\n${emitNode(child, depth + 1)}${pad}},\n`);
        }
    }
    return parts.join("");
}

export function emitResources(doc: OpenApiDocument): string {
    const tree = buildTree(buildOperations(doc));
    return `${HEADER}/* eslint-disable */
import type { Paginator } from "../core/pagination.js";
import type { Requester, RequestOptions } from "../core/requester.js";
import type { BodyOf, ItemOf, PathOf, QueryOf, ResponseOf } from "../core/types.js";

/** Every API operation, grouped by its operationId (\`listings.list\` → \`resources.listings.list\`). */
export function createResources(r: Requester) {
    return {
${emitNode(tree, 2)}    };
}

export type Resources = ReturnType<typeof createResources>;
`;
}

function routeOf(op: OperationInfo): RouteInfo {
    return { method: op.method, path: op.path, params: op.params, idempotent: op.idempotent, paginated: op.paginated };
}

export function emitRoutes(doc: OpenApiDocument): string {
    const lines = buildOperations(doc).map((op) => {
        const r = routeOf(op);
        return `    ${JSON.stringify(op.id)}: { method: ${JSON.stringify(r.method)}, path: ${JSON.stringify(r.path)}, params: ${JSON.stringify(r.params)}, idempotent: ${r.idempotent}, paginated: ${r.paginated} },`;
    });
    return `${HEADER}import type { RouteInfo } from "../core/catalog-types.js";

/** Method, path and wire details for every operation, keyed by operationId. */
export const ROUTES = {
${lines.join("\n")}
} as const satisfies Record<string, RouteInfo>;

export type RouteId = keyof typeof ROUTES;

/** Spec version these tables were generated from. */
export const API_VERSION = ${JSON.stringify(doc.info.version)};
`;
}

export function emitCatalog(doc: OpenApiDocument): string {
    const ops = buildOperations(doc);
    return `${HEADER}import type { OperationInfo } from "../core/catalog-types.js";

/** Full metadata (summaries, parameters, scopes) for every operation: drives the CLI and docs. */
export const CATALOG: readonly OperationInfo[] = ${JSON.stringify(ops, null, 4)};
`;
}

export function emitSchemas(doc: OpenApiDocument): string {
    const names = Object.keys(doc.components.schemas).sort();
    const lines = names.map((n) => `export type ${schemaAlias(n)} = components["schemas"][${JSON.stringify(n)}];`);
    return `${HEADER}import type { components } from "./openapi.js";

${lines.join("\n")}
`;
}

export function emitEvents(doc: OpenApiDocument): string {
    const events = buildEvents(doc);
    const map = events.map((e) => `${jsdoc([e.summary], INDENT)}    ${JSON.stringify(e.type)}: components["schemas"][${JSON.stringify(e.schema)}];`);
    return `${HEADER}import type { components } from "./openapi.js";

/** Webhook event type → typed payload (OpenAPI \`webhooks\` section). */
export interface HorusEventMap {
${map.join("\n")}
}

export type HorusEventType = keyof HorusEventMap;

/** Any v2 webhook event; narrow on \`event.type\`. */
export type HorusEvent = HorusEventMap[HorusEventType];

/** The event of one type: \`HorusEventOf<"sale.shipped">\`. */
export type HorusEventOf<T extends HorusEventType> = HorusEventMap[T];

export const EVENT_TYPES = ${JSON.stringify(events.map((e) => e.type))} as const satisfies readonly HorusEventType[];
`;
}

/** File name (under src/generated) → contents. openapi.ts comes from openapi-typescript. */
export function emitAll(doc: OpenApiDocument): Record<string, string> {
    return {
        "resources.ts": emitResources(doc),
        "routes.ts": emitRoutes(doc),
        "catalog.ts": emitCatalog(doc),
        "schemas.ts": emitSchemas(doc),
        "events.ts": emitEvents(doc),
    };
}
